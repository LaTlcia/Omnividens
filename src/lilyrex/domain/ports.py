"""Infrastructure-facing contracts; services never import concrete adapters."""
from __future__ import annotations
from typing import Iterator, Protocol
from .events import BattleEvent


class EventSource(Protocol):
    def events(self) -> Iterator[BattleEvent]: ...
    def close(self) -> None: ...


class ControlPort(Protocol):
    def send(self, user_id: int, room_id: str, command: str) -> tuple[bool, str]: ...
    def counts(self) -> tuple[int, int]: ...
    def stop_all(self) -> None: ...
